@pytest.mark.parametrize("files,suffix,want", [
    (["{n}-vertical-post.mp4", "{n}-vertical.mp4"], "-vertical-post.mp4", "{n}-vertical-post.mp4"),
    (["other-vertical-post.mp4"], "-vertical-post.mp4", "other-vertical-post.mp4"),
    (["{n}-vertical.mp4"], "-vertical-post.mp4", "no -vertical-post.mp4"),
    (["a-vertical-post.mp4", "b-vertical-post.mp4"], "-vertical-post.mp4",
     "2 -vertical-post.mp4 files, expected one"),
    (["{n}-vertical-post.mp4"], "-vertical.mp4", "no -vertical.mp4"),
    (["{n}-vertical.mp4"], "-vertical.mp4", "{n}-vertical.mp4"),
])
def test_exactly_one_video_ends_in_the_suffix(tmp_path, files, suffix, want):
    n = th_name(1)
    folder = tmp_path / n
    folder.mkdir()
    for f in files:
        (folder / f.format(n=n)).write_bytes(b"v")
    path, reason = yt.find_vertical_mp4(str(folder), suffix)
    want = want.format(n=n)
    if want.endswith(".mp4") and not want.startswith("no "):
        assert reason is None and os.path.basename(path) == want
    else:
        assert path is None and reason == want



def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def topfive_extras(root):
    """Folders the golden adds beside the eight fixtures, one per skip reason
    the intake has (none of them starts with ``_``: V3 changes that rule)."""
    os.makedirs(os.path.join(root, "notes"))
    _write(os.path.join(root, "C-020-no-video", "youtube.md"),
           "### YouTube Shorts\n- **Title:** t\n- **Description:** d\n- **Tags:** a\n")
    _write(os.path.join(root, "C-021-no-shorts", "youtube.md"), "## Notes\n- **Title:** t\n")
    _write(os.path.join(root, "C-021-no-shorts", "C-021-no-shorts-vertical.mp4"), "v")
    _write(os.path.join(root, "C-022-no-md", "C-022-no-md-vertical.mp4"), "v")
    _write(os.path.join(root, "C-023-two-videos", "youtube.md"),
           "### YouTube Shorts\n- **Title:** t\n- **Description:** d\n- **Tags:** a\n")
    for n in ("a-vertical.mp4", "b-vertical.mp4"):
        _write(os.path.join(root, "C-023-two-videos", n), "v")
    _write(os.path.join(root, "C-100-numbered-last", "youtube.md"),
           "### YouTube Shorts\n- **Title:** Last\n- **Description:** d\n- **Tags:** a, b\n")
    _write(os.path.join(root, "C-100-numbered-last", "C-100-numbered-last-vertical.mp4"), "v")
    # Unpadded, so name order and number order differ (C-50 before C-100).
    _write(os.path.join(root, "C-50-unpadded", "youtube.md"),
           "### YouTube Shorts\n- **Title:** Fifty\n- **Description:** d\n- **Tags:** a\n")
    _write(os.path.join(root, "C-50-unpadded", "C-50-unpadded-vertical.mp4"), "v")


def topfive_capture(env):
    """Everything the topfive commands print and store, with the temp root
    replaced by ``<TMP>`` so two runs compare."""
    topfive_extras(env["content_root"])
    steps = {}

    def run(name, fn):
        env["lines"].clear()
        code, _summary = fn()
        steps[name] = {"code": code, "lines": list(env["lines"])}

    run("import", lambda: yt.import_history(PROFILE, now=NOW, out=env["out"]))
    run("intake_dry", lambda: yt.intake(PROFILE, dry_run=True, now=NOW, out=env["out"]))
    run("intake", lambda: yt.intake(PROFILE, now=NOW, out=env["out"]))
    give_token(env)
    mark_moved(env)
    run("schedule_dry", lambda: yt.schedule(PROFILE, dry_run=True, now=NOW,
                                            api=FakeApi(), out=env["out"]))
    run("status", lambda: yt.status(PROFILE, now=NOW, out=env["out"]))
    steps["state"] = state(env)
    text = json.dumps(steps, indent=1, sort_keys=True, ensure_ascii=False)
    tmp = str(env["tmp"])
    for form in (tmp, tmp.replace("\\", "/"), json.dumps(tmp)[1:-1]):
        text = text.replace(form, "<TMP>")
    return json.loads(text.replace("\\\\", "/"))


def test_topfive_matches_the_golden_taken_before_v3(env):
    with open(GOLDEN, encoding="utf-8") as f:
        golden = json.load(f)
    got = topfive_capture(env)
    assert set(got) == set(golden)
    for step in golden:
        assert got[step] == golden[step], step


def test_the_golden_covers_every_skip_reason_and_number_order():
    """The golden is only a proof if it exercises the paths V3 touched."""
    with open(GOLDEN, encoding="utf-8") as f:
        golden = json.load(f)
    lines = "\n".join(golden["intake"]["lines"])
    for needle in ("SKIP (not a video folder): _posted/",
                   "SKIP (not a video folder): ready-to-publish/",
                   "SKIP (not a C-NNN-<slug> folder): notes/",
                   "SKIP (no -vertical.mp4): C-020-no-video",
                   "SKIP (no YouTube Shorts section in youtube.md): C-021-no-shorts",
                   "SKIP (no youtube.md): C-022-no-md",
                   "SKIP (2 -vertical.mp4 files, expected one): C-023-two-videos",
                   "ADDED: C-100-numbered-last"):
        assert needle in lines, needle
    assert lines.index("ADDED: C-50-unpadded") < lines.index("ADDED: C-100-numbered-last")
    items = golden["state"]["items"]
    assert items["C-100-numbered-last"]["c_number"] == 100
    assert any(r["origin"] == "video-publisher" for r in items.values())
    assert sum("WOULD" in x for x in golden["schedule_dry"]["lines"]) >= 2



# ── synthetic copies of the six real title_sections files ──────────────────

#: number -> (slug, tag count, hashtag count), as in the six real files.
TH_LAYOUTS = {1: ("the-family-drawing", 11, 7), 2: ("emergency-alert", 13, 7),
              3: ("delivery-photo", 13, 7), 4: ("babysitter-rules", 14, 7),
              5: ("grandmas-voicemail", 14, 8), 6: ("thirteen-steps", 14, 8)}


def th_name(n):
    return "TH-%03d-%s" % (n, TH_LAYOUTS[n][0])


def th_expected(n):
    _slug, ntags, nhash = TH_LAYOUTS[n]
    paras = ["Synthetic hook %d. A second sentence, with a comma." % n,
             "A synthetic series line.",
             "A synthetic one-liner %d." % n,
             " ".join("#synth%d" % i for i in range(nhash))]
    return {"title": "Synthetic Title %d. A Second Clause. #shorts" % n,
            "description": "\n\n".join(paras),
            "tags": ["synthetic tag %d" % i if i % 3 else "tag%d" % i for i in range(ntags)]}


def th_md(n, eol="\n"):
    name = th_name(n)
    exp = th_expected(n)
    lines = ["# TH-%03d Synthetic %d: YouTube Shorts" % (n, n), "",
             "Post: %s-vertical-post.mp4 (1.0 MB, 50 s, 9:16). Thumbnail: "
             "%s-poster-vertical.png. A note that is not metadata." % (name, name), "",
             "## Title", exp["title"], "",
             "## Description"]
    for i, para in enumerate(exp["description"].split("\n\n")):
        if i:
            lines.append("")
        lines.append(para)
    lines += ["", "## Tags", ", ".join(exp["tags"])]
    return eol.join(lines) + eol


def parsed(text):
    return yt.metadata_fields(text, "title_sections")


@pytest.mark.parametrize("n", sorted(TH_LAYOUTS))
def test_each_title_sections_file_parses_verbatim(n):
    fields, reason = parsed(th_md(n))
    assert reason is None
    assert fields == th_expected(n)
    assert len(fields["description"].split("\n\n")) == 4
    assert fields["description"].split("\n\n")[-1].startswith("#synth0 ")
    assert len(fields["tags"]) == TH_LAYOUTS[n][1]
    # The H1 and the Post/Thumbnail paragraph are not metadata.
    blob = json.dumps(fields)
    assert "Post:" not in blob and "Thumbnail" not in blob and "YouTube Shorts" not in blob


def test_title_sections_handles_crlf_and_a_bom(env, tmp_path):
    folder = tmp_path / th_name(1)
    folder.mkdir()
    (folder / "youtube.md").write_bytes(b"\xef\xbb\xbf" + th_md(1, "\r\n").encode("utf-8"))
    (folder / (th_name(1) + "-vertical-post.mp4")).write_bytes(b"v")
    fields, reason = yt.read_item_folder(str(folder), "-vertical-post.mp4", "title_sections")
    assert reason is None
    media = fields.pop("media_path")
    assert fields == th_expected(1)
    assert media.endswith(th_name(1) + "-vertical-post.mp4")


def test_a_title_body_runs_to_the_next_heading_of_any_level():
    text = ("## Title\nThe title\n### Note\nnot the title\n"
            "## Description\nPara one.\n\n#tag1 #tag2\n# Appendix\nnot description\n"
            "## Tags\na, b ,c,\n#### Later\nd, e\n")
    fields, reason = parsed(text)
    assert reason is None
    assert fields == {"title": "The title", "description": "Para one.\n\n#tag1 #tag2",
                      "tags": ["a", "b", "c"]}


def test_a_multi_line_title_joins_to_one_line_and_indent_is_dropped():
    text = "## Title\n  Part one\n part two  \n## Description\n  d\n## Tags\nx\n"
    assert parsed(text)[0]["title"] == "Part one part two"
    assert parsed(text)[0]["description"] == "d"


def test_sections_can_come_in_any_order_and_heading_case_does_not_matter():
    text = "## tags\nx, y\n## DESCRIPTION\nd\n## Title\nt\n"
    assert parsed(text)[0] == {"title": "t", "description": "d", "tags": ["x", "y"]}



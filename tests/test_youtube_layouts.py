def test_teratoma_numbers_order_dates_numerically_not_by_name(th_env):
    env = th_env
    # By name TH-010 sorts before TH-9; by number it comes after.
    extra = ["TH-9-ninth", "TH-010-tenth"]
    for name in extra:
        _write(os.path.join(env["content_root"], name, "youtube.md"), th_md(2))
        _write(os.path.join(env["content_root"], name, name + "-vertical-post.mp4"), "v")
    code, s = yt.intake(PROFILE, now=NOW, out=env["out"])
    assert s["new"] == [th_name(n) for n in range(1, 7)] + extra
    st = state(env)
    assert st["items"]["TH-9-ninth"]["c_number"] == 9
    assigned = yt.assign_dates(st, yt.youtube_config(PROFILE), NOW)
    assert [i for i, _at in assigned] == [th_name(n) for n in range(1, 7)] + extra
    days = [yt.parse_instant(at).astimezone(yt.PACIFIC) for _i, at in assigned]
    assert all(d.hour == 12 and d.minute == 0 for d in days)
    assert len({d.date() for d in days}) == 8



def test_teratoma_intake_queues_the_six_in_number_order(th_env):
    env = th_env
    before = tree(env["content_root"])
    os.makedirs(os.path.join(env["content_root"], "C-007-wrong-prefix"))
    code, s = yt.intake(PROFILE, now=NOW, out=env["out"])
    assert code == 0
    assert s["new"] == [th_name(n) for n in range(1, 7)] and s["skipped"] == []
    assert "  SKIP (not a video folder): _superseded/" in env["lines"]
    assert "  SKIP (not a TH-NNN-<slug> folder): C-007-wrong-prefix/" in env["lines"]
    items = state(env)["items"]
    for n in TH_LAYOUTS:
        rec = items[th_name(n)]
        assert rec["c_number"] == n and rec["status"] == yt.QUEUED
        assert rec["media_path"].endswith(th_name(n) + "-vertical-post.mp4")
        assert {k: rec[k] for k in ("title", "description", "tags")} == th_expected(n)
        assert rec["source_folder"] == os.path.join(env["content_root"], th_name(n))
    os.rmdir(os.path.join(env["content_root"], "C-007-wrong-prefix"))
    assert tree(env["content_root"]) == before    # content is only read


